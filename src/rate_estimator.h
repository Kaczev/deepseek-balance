// ===========================================================================
//  rate_estimator.h —— 消耗速率估计与"还剩多久清零"的分支判定（设计 §7.2 §7.4）
// ===========================================================================
//
//  ★ 本模块是**纯函数**：不读时钟、不碰文件、没有全局量、不抛异常。
//    输入是"最新若干个点（金额 + 各点自己的时间）"，输出是一个小的结果结构。
//    外面谁调用都行：探针、自检、窗口每帧逻辑。正因为没有隐藏状态，
//    离线探针（tools/rateprobe.cpp）能拿合成序列把这里的每条规则都证明一遍。
//
//  设计出处：`不入库文件/v0.2 设计.md` §7.2（正跳变）与 §7.4（清零预估的五个分支）。
//
//  ⚠ 与设计文档**有意不同**的几处（所有者的决定，不要"修回去"）：
//    1. §7.3 的**稳健回归**不实现。所有者 2026-09-16 定了更简单、对他那种情况更准的
//       口径：**逐个台阶取下降量之和**（见下面 §7.2/§7.3 那一节）。
//       这一节**被改过两次**，两次的教训都留在注释里，因为它们都是"看起来更聪明、
//       实际更糟"的写法：
//         · 第一版：对时间拟合斜率（最小二乘）。问题在 §7.2 那一节。
//         · 第二版：先剔除正跳变、再拟合。问题依旧——**一次回升就把整个窗口作废**，
//           于是"余额涨过一次"的账户永远报「暂无法预测」。探针 case3 是这条回归的守门人。
//    2. §7.3 的**赠金过期识别**不实现（接口不给流水，分不出"过期"和"消费"）。
//       代价写在 EstimateRate 的注释里，别当成漏做。
//
//  ★ §7.3 的**计算窗口**与设计文档取不同的长度：文档写 2 小时，这里默认
//    kRateWindowSeconds = 1800 s（30 分钟，见 tuning.h）。
//    窗口**实现着、并用着**（rate_estimator.cpp 的 EstimateRate：按最新点的时间
//    减去 kRateWindowSeconds 只留最近这一段），不是漏做——它正是为抖动加的：
//    纯抖动、零真实消耗时，"下降量之和 ÷ 跨度"被越拉越长的跨度稀释，
//    所有者实测底部文案从 7.4 小时一路爬到 31.4 小时、再到「超过 7 天」。
//    点数不设上限（文档也没有）：调用方给几个点就按几个点算。
//    要改窗口长度改 tuning.h 的那一个常量；0 = 关闭窗口、回到"所有点都进"。
//
// ---------------------------------------------------------------------------
// §7.2 §7.3 ★ 所有者的口径：消耗 = 只把**下降**的台阶加起来
// ---------------------------------------------------------------------------
//      消耗 = Σ max(0, 前一点 − 后一点)                —— 只累加下降的台阶
//      速率 = 消耗 / (最老到最新一个可用点之间的跨度)     —— 元/分钟
//  三条后果，都是这条口径**故意**要的：
//    1. 速率**永远不为负**：分子是若干个 max(0,·) 之和，跨度是正的。
//    2. **回升不作废窗口**（这就是那次回归修复）：充值/赠金只让**它自己那一个台阶**
//       贡献 0，其余台阶照常算，时间照样算——充值之后接着花这种最常见的场景，
//       于是能读出速率。回升不是"负消费"，它只是"这一小段时间没花钱"。
//       ★ 旧口径的病根：把回升的那个点**丢出窗口**，于是回升之后每个点都比前一个低水位
//         高、全被判成跳变丢掉，一次充值就把跨度和样本一起打没 -> 不显著 -> 永远
//         「暂无法预测」。所有者要的正是"涨过一次也照样报得出速率"。
//    3. 一个下降台阶都没有的窗口 -> 速率**恰好 0**，status = NotConsuming
//       （不是"不显著"：那段确实没在花钱，这是个结论，不是读不出来）。
//
// ---------------------------------------------------------------------------
// §7.4 的五个分支（底部文案）
// ---------------------------------------------------------------------------
//  速率不显著 -> 「暂无法预测」
//  速率 == 0  -> 「—」（= 没在消耗；速率永不为负，所以破折号**恰好**给 0）
//  余额为 0   -> 「已用尽」
//  剩余 > 7 天 -> 「超过 7 天」（**故意封顶**，不给一个没人信的精确值）
//  其它       -> 「按当前速度，约 2 小时后归零」，剩余 ≤ 6 小时时再补一个绝对时刻
//  文案里的中文与文档**逐字一致**，这是给人看的字符串，不许改写。
//  ※ "速率 == 0 -> 破折号"这一条与设计文档 §7.4 表格里的「速率 ≤ 0」一一对应：
//    速率不会为负，于是 ≤ 0 与 == 0 是同一件事，这里按**新的**口径写 ==。
#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace dshb {

// ---------------------------------------------------------------------------
// 输入：一个点
// ---------------------------------------------------------------------------
//  `amountRaw` 直接用 amount.h 的定点单位（1/10000 元）。做成定点而不是 double，
//  是为了和存储层、金额层用同一套数：这里是"钱的比较"，不该另开一条浮点路径。
//  换算成"元/分钟"只在最后做一次（见 .cpp）；速率本来就是估计值。
struct RateInputPoint {
    int64_t at = 0;             // epoch 秒，这一点自己的时间（curve_store §2.3b）
    bool atValid = false;       // false = 没有时间可用（老文件里的点）
    bool amountValid = false;   // false = 这个点没有可用金额（缺币种 / 解析失败）
    int64_t amountRaw = 0;      // 定点金额，1/10000 元
};

// ---------------------------------------------------------------------------
// 输出：状态
// ---------------------------------------------------------------------------
//  ★ 语义按**速率**定（速率是"元/分钟"的**大小**，永远 ≥ 0）：
//    有下降、够显著 -> rate > 0 -> Significant（余额在掉）
//    一个下降台阶都没有 -> rate == 0 -> NotConsuming（平的，或只在回升）
//    ★ `Rising` 这个名字被换掉过一次，原因值得留着：旧口径下速率是斜率，可以为负，
//      "Rising" 指的是"速率为正 = 余额在涨"，可**平的**余额也是它——于是一个"不消耗"
//      的状态叫"Rising"，读代码的人（和后来改文案的人）都会被这个名字带偏。
//      现在平的和回升都是同一件事：**没在消耗**，所以叫 NotConsuming。
enum class RateStatus {
    Empty,          // 没有任何点携带可用金额
    Insignificant,  // 不显著：下降台阶不够、跨度不到 5 分钟、或有点没有自己的时间
    NotConsuming,   // 速率恰好 0：窗口里一个下降台阶都没有（平的，或只在回升）
    Significant,    // 显著的消耗：速率 > 0（元/分钟），余额在掉
};

const char* RateStatusName(RateStatus status);

// ---------------------------------------------------------------------------
// 输出：结果
// ---------------------------------------------------------------------------
struct RateEstimate {
    RateStatus status = RateStatus::Empty;

    // 元/分钟，**永远是大小**（≥ 0）。只有 status == Significant 时它 > 0；
    // NotConsuming 时它恰好是 0（"没在消耗"是个结论）；Insignificant / Empty 时
    // 它是 0，含意是"没有数字"，调用方不许把它当数字用（这正是"不许编一个数"那条）。
    double rateYuanPerMinute = 0.0;

    // 取整之前的原始速率，未取整。**只看不判**：不显著的结论里也照记，
    // 因为"测到了多少"和"肯不肯报"是两件事——每个 no 长得一样就没法读。
    double rawRateYuanPerMinute = 0.0;

    // 诊断用，全部是"看到了什么"，不参与判定：
    int pointsSeen = 0;        // 调用方给了几个点
    int usablePoints = 0;      // 金额与时间都可用的点：**全部**留在窗口里（不剔除任何点）
    int decreasingSteps = 0;   // 其中下降的台阶数——显著性判据数的就是它
    int risingSteps = 0;       // 上升的台阶数（诊断：它们只贡献 0，不作废窗口）
    int64_t dropSumRaw = 0;    // 下降台阶之和（定点）——就是分子
    int undatedPoints = 0;     // 没有时间的点（连续的没时间点算一段，见 .cpp）
    int unusablePoints = 0;    // 没有可用金额的点
    int64_t spanSeconds = 0;   // 最老到最新一个可用点之间的跨度
    std::string note;          // 一句话说明为什么是不显著；显著时也留着"看到了什么"
};

// ---------------------------------------------------------------------------
// §7.3 的估计本体（纯函数）
// ---------------------------------------------------------------------------
//  输入顺序：**旧 -> 新**（和 CurveStore::Points() / Newest() 一致）。
//
//  规则（顺序就是实现顺序，别调换）：
//    1. 没有可用金额的点、没有时间的点：只记诊断，不进窗口。
//       ★ 只要序列里出现了一个"没有时间"的点，结果就是**不显著**：一部分点的
//         时间不存在时，任何"元/分钟"都必须先假设点距（比如假设 10 秒），而那
//         正是所有者禁止的假设。宁可说"暂无法预测"，也不给一个基于假设的数字。
//    2. ★ 窗口 = 金额和时间都可用的点，**一个都不剔除**。回升的点留在窗口里：
//       它贡献 0（分子只加下降量），但它的**时间**要留在跨度里——那段时间确实过去了。
//       （旧口径把回升的点丢掉，一次充值就把跨度和样本一起打没；见文件顶部第 2 条。）
//    3. 分子 = Σ max(0, 前一点 − 后一点)。**没有下降台阶**（分子恰为 0 台阶数）时
//       速率**恰好 0**、status = NotConsuming，这一条**排在两条显著性判据之前**：
//       "这段没在花钱"本身就是结论，不该被"样本不够"顶掉。
//    4. 不显著的两条硬判据（所有者的旧决定，照旧）：**下降的台阶少于
//       kRateMinDecreasingSamples 个**，或**跨度不到 kRateMinSpanSeconds**。
//       没有这两条，两个台阶就能编出"3 年后归零"。
//    5. 速率 = 分子 / 跨度，换算成元/分钟；取整到 kRateRoundDigitsYuanPerMinute 位。
//       取整后为 0 就**不报**（不显著）：报一个 1e-11 元/分钟等于编了个数字。
//       真实数据到不了这一步（跨度上限 86400 s、最小下降 1 raw 也还有 6.9e-8 元/分钟），
//       它只是把"不许报 0 以外的假数字"这条写死。
RateEstimate EstimateRate(const std::vector<RateInputPoint>& pointsOldestFirst);

// ---------------------------------------------------------------------------
// §7.3 末尾那道弹簧：rate_display 追 rate
// ---------------------------------------------------------------------------
//  ★ 这里同样没有隐藏状态：调用方持有 rateDisplay，每帧把它自己交回来。
//    这就是"纯函数"和"平滑"能同时成立的做法，也让探针能把收敛过程逐帧量出来。
//  * 半隐式/指数形式，**绝不越过目标**：返回值被夹在 {旧值, 新值} 之间，所以
//    阶跃输入下是单调收敛、没有过冲（验收项 7）。
//  * dt 夹在 [0, kRateSpringMaxDtSeconds]（50 ms，设计 §9.6 的 dt 钳制）：否则
//    休眠唤醒后的第一帧 dt 巨大，一步就跳到位，等于没有弹簧。
//  * dt <= 0 -> 原样返回当前值（不能倒着走）。
double RateSpringStep(double rateDisplay, double rateTarget, double dtSeconds);

// ---------------------------------------------------------------------------
// §7.4 底部文案
// ---------------------------------------------------------------------------
enum class ZeroTimeKind {
    None = 0,        // 这一行不该出现（余额未知 / 欠款 / 为 0 由调用方决定）
    NoPrediction,    // 「暂无法预测」
    Dash,            // 「—」
    UsedUp,          // 「已用尽」
    OverSevenDays,   // 「超过 7 天」
    Extrapolated,    // 「按当前速度，约 …」
};

const char* ZeroTimeKindName(ZeroTimeKind kind);

struct ZeroTimeText {
    ZeroTimeKind kind = ZeroTimeKind::None;
    std::wstring text;   // UTF-16：窗口是 Win32 + DirectWrite，最终要的就是这个
    int minutesToZero = -1;   // 未取整的估算分钟数；"算不出来"时是 -1
};

//  balancedRaw < 0  -> None（欠款：说"几小时后归零"是废话）
//  balancedRaw == 0 -> UsedUp（余额真的用尽了，和"不显著"是两回事）
//  ★ 五种分支的判定顺序（顺序本身就是规格，见 .cpp）
//
//  `nowEpochSeconds` 只用来把一个绝对时刻写成本地时间（§7.4：绝对时刻以本地时钟
//  为准，且必须和相对时长在同一段文案里）。它**不参与速率估计**——EstimateRate 里
//  没有时钟，这条边界不要模糊掉。
ZeroTimeText ZeroTimeFor(const RateEstimate& estimate, int64_t balancedRaw, int64_t nowEpochSeconds);

// ---------------------------------------------------------------------------
// §7.4「数值变化 < 10% 时不重绘」
// ---------------------------------------------------------------------------
//  这个"上一次画的是什么"的记忆由窗口持有（本模块不留静态量），每帧原样传进来。
//  ★ 注意：窗口每帧走的是 ZeroTimeFor（每次重算），不是这个带记忆的版本。
//    这个版本留给"要让数字不乱跳"的调用方，探针 case8 逐条量着它。
struct ZeroTimeRenderState {
    bool have = false;              // 上一次算过吗
    ZeroTimeKind kind = ZeroTimeKind::None;   // 上一次画的是哪个分支
    int minutesToZero = -1;         // 上一次画的分钟数（取整后）
    double rateYuanPerMinute = 0.0; // 上一次画时用的速率
    std::wstring text;              // 上一次画的那行字
};

//  返回**这一帧应该画的字**，并就地更新 state。
//  * 数字没变、或变化不到 10% -> 返回上一次的字符串（不重绘，避免数字乱跳）
//  * 分支变了（"能预测了 / 不能预测了"）-> 一定重画
//  * 分支没变、但上一帧是显式重绘（force）-> 也重画
std::wstring ZeroTimeTextForFrame(const RateEstimate& estimate, int64_t balancedRaw,
                                  int64_t nowEpochSeconds, ZeroTimeRenderState* state);

}  // namespace dshb
