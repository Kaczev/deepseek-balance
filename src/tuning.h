// 3d. 归零预测的新口径（所有者 2026-09-19 定案：Theil–Sen 中位斜率）
// ---------------------------------------------------------------------------
//  为什么换公式：上面那套"下降量之和 ÷ 跨度"把**停机空档**算进了分母。跨度取的是
//  "最旧→最新"，而余额没变的那段时间里没有任何点、也没有任何下降量，于是那段空档
//  只把分母拉长、不贡献分子——速率被稀释、预估值一路往上爬（所有者实测 12 个点跨
//  137.9 分钟 -> 预测 42.4 小时）。
//  ★ 注意：**加大采样密度不解决这个问题**。"余额没变就不记点"是曲线规格 §2.1 的
//    核心，而密度对"总和 ÷ 总跨度"完全无效：不变的点 drop=0 不进分子，最旧那个点
//    也没变，所以分母也不动。病在公式，不在采样密度——所以要换的是公式。
//  ★ 新口径：窗口内**所有点对**的斜率取中位数（Theil–Sen）。一个跨越停机空档的点对
//    给出的斜率接近 0，它只是中位数里的一票，而不再是"把整段速率拉低"的全部。
//  新旧两条链并存（见 rate_estimator.h 的"哪个是哪个"）：曲线/氛围那条链还在用旧的。

// ★ 窗口内点数上限**不需要**（120 个点 => 120×119/2 = 7140 个点对，一次算完是微秒级；
