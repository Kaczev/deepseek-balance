// ---- 5.6 剧烈程度 R 的恢复速度（所有者 2026 定的模型）----
//  R(t) = kAmbienceDecayA ^ t        t 的单位是**分钟**
//  每帧 t += dt；每次数据刷新算出新的 R（= R_new，就是曲线端点要用的那个量），
//  若它 **高于**当前的 R(t)，则令 t = ln(R_new) / ln(a) —— 也就是"跳到新高度、再从那里
//  自己往下落"；若 R_new **低于** R(t)，则什么都不做（它被当前的 R(t) 盖过去了）。
//  于是 R 的响应永远是"跳上去、然后自己慢慢落回来"，不需要任何逐通道缓动：
//  颜色本身就是 R(t)、D 的纯函数。
//
//  ★ 这是**唯一**描述"剧烈之后多久平静下来"的数。取 a = 0.5 就是"半衰期恰好 1 分钟"：
//      R 半衰期   = ln 2 / (-ln a) = 1.0 分钟
//      R 时间常数 = 1 / (-ln a)    = 1.4427 分钟（R 落到 1/e）
//      一帧（1/60 s）的衰减系数 = exp(ln a / 3600) = 0.9998075
//    想要"平静得更快"就取 0.1（半衰期 18.1 秒），想要"余韵更长"就取 0.8（半衰期 3.1 分钟）。
//  必须严格落在 (0,1)：a >= 1 时 R 不衰减（颜色永远停在血色），a <= 0 无意义。
inline constexpr double kAmbienceDecayA = 0.5;
// 每帧推进的 dt 上限（秒）。与 kRateSpringMaxDtSeconds 同一个值、同一个理由：
// 休眠唤醒后第一帧 dt 巨大，动画会一步跳到位。R 的衰减与蒙光强度的缓动共用它。
inline constexpr double kAmbienceDtMaxSeconds = 0.05;

// ---- 5.7 蒙光强度的缓动 ----
//  ★ 只有**强度**还在缓动，颜色不缓动（颜色的平滑由 5.6 的 R(t) 负责）。
//  强度用连续解 exp(-dt/τ)，与帧率无关；dt 用上面那个上限。
//  τ = 1.5 s 是当初设计里"光晕透明度 1.5 s"那个数，没有别的来源。
inline constexpr float kGlowInTauSeconds = 1.5f;

// ---- 5.8 关闭态（设计 §10.2）：R 的两个下限 + "紧张"动画的三个数 ----
//
//  ★ R 的下限为什么放在这里：R 是**氛围**的量，与 R(t) = a^t（5.6）是同一条链。
//    两次点击各把下限抬一档，而"抬"走的就是数据刷新那一条路（5.6 的抬升规则）：
//        第 1 击  R = max(R_new, R_d1)      第 2 击  R = max(R_new, R_d2)
//    于是光晕颜色与心跳周期/幅度**都**拿到这个下限 —— 心跳按 R 取律（§6.2、§6.3），
//    它读的就是同一个 R，所以不需要第二处下限（两处各写一次必然分叉）。
//  ★ 取值 0.5 / 1.0 不是随手挑的：它们正好是颜色管线两个锚点
//    （0.5 = #f6aa6c 橙、1.0 = #f66c6c 血色，见 5.2），于是两档在屏幕上可辨且可量。
inline constexpr double kShutdownRd1 = 0.5;   // 第 1 击后的下限
inline constexpr double kShutdownRd2 = 1.0;   // 第 2 击后的下限

//  进入段（右键那一刻起）的帧数：旧内容在这段时间里被抽走、抖动从最大收到常态。
