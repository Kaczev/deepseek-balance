// 里程表带子的算法（与渲染无关，可单独测试）
//
// ★ 为什么把这段单独拿出来：数字滚动的实现我连续做错了四版，每一版都靠
//   "导出图、看形状、猜原因"来推进，代价是几小时。把算法抽成纯函数之后，
//   它可以用断言直接验证——**"形状对了但内容错"这类问题本来就该由测试发现，
//   不该由眼睛发现**。

#pragma once

#include <string>
#include <vector>

namespace dshb {

// 一条"该画哪个数字"的指令。
// 字段顺序按概念顺序排：先说是哪一位，再说这一位画什么、画在第几行、在行间偏多少。
struct WheelDraw {
    int slot = 0;          // 属于第几位（text 里的下标）
    int digit = 0;         // 这一位上要画的数字 0..9
    int row = 0;           // 相对"落位行"的偏移：0 = 落位那一行，1 = 它下面一行
};

// 由"文本 + 该文本对应的金额"算出每一位该画哪些数字。
//
// ★ 位权的正确算法（第一版错在这里，代价是一次完整返工）：
//   字符串下标 **不等于** 十进制位次。必须按"这个字符在小数点前还是后、
//   是第几个"来定位权：
//     小数点前的第 p 个（从 0 数）-> 10^(整数位总数 - 1 - p)
//     小数点后的第 q 个（从 0 数）-> 10^-(q + 1)
//   例："34.56" -> '3' 是 10^1、'4' 是 10^0、'5' 是 10^-1、'6' 是 10^-2。
//   第一版用的是"该字符右边还有几个数字字符"，对小数字恰好错位，
//   症状看起来像"整体缩小了 100 倍"——其实不是缩放，是位权映射错了。
//
// 于是：
//   第 p 位的连续值 wheelValue = 金额 / 该位位权
//   第 d 个数字画在 (d - wheelValue) 行处
//   窗口只露一行，所以只有 floor(wheelValue) 与 floor(wheelValue)+1 可能落在里面
//
// 关键不变式（测试断言这一条）：**row == 0 的那些数字，按 slot 顺序连起来
// 必须等于文本自身的数字**。这一条成立，画面上看到的就是余额本身。
std::vector<WheelDraw> ComputeWheel(const std::string& text, double amount);

// 某一位的"连续值"（小数点后若干位）。渲染层要用它算带子在两行之间的位置。
// ★ 单独导出这一个函数，是为了让**渲染层不必自己再算一遍位权**——
//   第一版两边各算一份、含义不一致，于是带子被整体挪偏了一行。
//   位权只允许在这里实现一次。
// @param text   形如 "34.56"
// @param slot   text 里的字符下标（必须指向数字字符）
// @param amount 当前金额
// @param out    输出：该位的连续值；slot 不是数字字符时返回 false
bool WheelValueAt(const std::string& text, int slot, double amount, double* out);

// 诊断开关（由 --selftest-b 打开）：把每次调用收到的文本、金额与逐步中间量
// 写进 wheel-trace.log。
extern bool g_wheelTrace;

// 诊断输出的目录。由 main.cpp 在启动时写入（绝对路径）——**不要用相对路径**：
// 双击运行时工作目录往往不是 exe 所在目录，写进去的日志等于丢了。
extern std::string g_wheelTraceDir;

}  // namespace dshb
